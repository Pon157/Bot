def ce(emo: Emo) -> str:
    """
    Возвращает HTML-обёртку для premium-эмодзи, подходящую для parse_mode='HTML'.
    Если у бота/пользователя нет доступа к custom emoji (не premium) — Telegram
    сам красиво деградирует в отображении обычного fallback-символа внутри tg-emoji.
    """
    return f'<tg-emoji emoji-id="{emo.custom_id}">{emo.fallback}</tg-emoji>'


def plain(emo: Emo) -> str:
    """Просто fallback-символ, без разметки (для callback_data, alert-ов, кнопок без HTML)."""
    return emo.fallback
